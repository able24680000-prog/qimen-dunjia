# -*- coding: utf-8 -*-
"""断语金标准回测（V2.5 确定性成败倾向 vs 《神奇之门》原著应验结局）。

原理与边界
----------
1. `verdict_tendency` 是纯确定性代码：只读主用神的格局吉凶/落空/门迫/月令/
   生克/盘眼减分，不含任何随机性，也不读案例库——因此本回测可复跑、可复核，
   不存在"LLM 看过结局"的失真问题。
2. 金标准仅收录**二值成败可判定**的案例；教学片段、无断语、非二值事项
   （名次细节/伤亡/时局）不进入统计，逐条列明排除原因，不凑数。
3. 未命中分两类口径：
   - 「口径分歧」：原著断法与本包裁决口径对同一信号判向不同（如落空伤门
     因生值符仍判可用），属流派差异，不为刷分而改；
   - 「真误断」：本包评分链路自身的问题，逐条修。
4. 问项措辞取原著当事人的自然问法；触发词未覆盖的钉定 topic 并注明。
"""
import sys
from pan_engine import pan
from analyze import analyze
from event_scope import resolve_scope

# (案例id, 金标准, 事件大类, 原著问项(自然措辞), 可观察结果, topic钉定或None, 备注)
GOLD = [
    ('06', '败', '婚姻',    '男方测婚姻能否维持',       '双方关系维持',   None,       '原著应验：离婚，女方先提；乙庚对冲主散'),
    ('07', '败', '婚姻',    '男方测婚姻能否维持',       '双方关系维持',   None,       '原著应验：丈夫外遇决意离；乙克庚主散'),
    ('11', '成', '考试',    '替孩子问升学能否考上大学', '收到录取通知',   None,       '代测子女：主用神应取时干'),
    ('12', '成', '事业官运', '这次选举能否取得理想名次', '名次如意',       None,       '原著应验：名次全中'),
    ('14', '败', '求财',    '合资办厂这件事能否办成',   '签约并投产',     None,       '原著应验：合资落空'),
    ('15', '成', '求财',    '这笔欠款能否讨回',         '如数收回欠款',   None,       '旧款回收细分：主用神伤门；落空口径分歧'),
    ('17a', '成', '走失',   '孩子走失能否找回',         '人平安找回',     None,       '问测局；人员走失细分'),
    ('17b', '成', '走失',   '孩子走失能否找回',         '人平安找回',     None,       '走失局；人员走失细分'),
    ('18', '成', '走失',    '发票丢了能否找到',         '物品找到',       '物品遗失',  '原著：反吟+内盘主快'),
    ('19', '成', '走失',    '身份证丢了能否找到',       '物品找到',       '物品遗失',  '原著：时干癸生日干主能找到'),
    ('20', '成', '走失',    '被偷的钱能否追回',         '款项追回',       '物品遗失',  '原著以玄武取贼像、生门取数'),
    ('21', '成', '官司',    '父被诬告这场官司能否脱身', '尽快获释',       None,       '原著应验：次日获释'),
    ('25', '成', '天气',    '仪式时段何时雨停',         '如期雨停',       None,       '雨停转晴细分：天蓬反向口径'),
]

EXCLUDED = [
    ('01/02', '教学片段，无断语'),
    ('03/04/05/26', '健康/阴宅起局片段，原著无成败结局'),
    ('08/09/10', '求子生产：事件包无对应大类（为忠实原著取用，不强行映射到婚姻/健康）'),
    ('13', '长期项目，非二值成败'),
    ('16', '走失结局含伤亡双义，按安全边界不进二值统计'),
    ('22/23', '竞技预测：事件包无对应大类'),
    ('24a/b/c', '时局趋势：事件包无对应大类'),
    ('27', '择居方案比选，原著未给应验结局'),
]


def main():
    import original_cases as oc
    rows, hit_s, hit_l = [], 0, 0
    for cid, gold, cat, q, obs, topic, note in GOLD:
        c = oc.by_id(cid)
        d = pan(c['gz'], c['ju'])
        scope = resolve_scope(cat, q, obs, topic=topic)
        pkg = analyze(d, cat, scope=scope)
        t = pkg['tendency']
        shen = scope['主用神']
        verdict = t['倾向']
        strict = (verdict == gold)
        lenient = strict or (verdict == '两可')
        hit_s += strict
        hit_l += lenient
        rows.append((cid, gold, verdict, t['得分'], t['信心'], shen, scope['问项'], strict, lenient, t['证据']))
        mark = '✅' if strict else ('◐' if lenient else '❌')
        print(f"{mark} {cid:3} 金={gold} 算={verdict}({t['得分']:+g},{t['信心']}) "
              f"用神={shen}@{scope['问项']} {note}")
        if not strict:
            for e in t['证据']:
                print(f"      · {e}")
    n = len(GOLD)
    print(f"\n严格命中（成/败完全一致）: {hit_s}/{n} = {hit_s/n:.0%}")
    print(f"宽口径命中（两可记半）  : {hit_l}/{n} = {hit_l/n:.0%}")
    print(f"排除案例: {len(EXCLUDED)} 组（见 EXCLUDED 逐条原因）")
    misses = [r for r in rows if not r[7]]
    if misses:
        print("\n未命中明细（供口径分歧/真误断分类）:")
        for r in misses:
            print(f"  {r[0]} 金={r[1]} 算={r[2]}({r[3]:+g}) 用神={r[5]}")
    return rows


if __name__ == '__main__':
    main()
