def resolve_scope(category, question, outcome, *, topic=None, parties=None, roles=None,
                  first_mover=None, urgency=None, stage=None, horizon=None, primary=None):
    rules = QUESTION_RULES.get(category, {})
    hits = [name for name, rule in rules.items() if any(word in question for word in rule.triggers)]
    # 多个关键词命中时保留分歧，调用方可按主问题明确指定。
    if topic is not None and topic != '通用' and topic not in rules:
        raise ValueError('问项与类别不匹配，可选：' + '、'.join([*rules, '通用']))
    chosen = topic or (hits[0] if len(hits) == 1 else '通用')
    rule = rules.get(chosen)
    symbols = list(dict.fromkeys([rule.primary, *rule.support, '值使'])) if rule else [
        *dict.fromkeys([*CATEGORY_SHEN[category], '值使'])]
    if primary is not None and primary not in symbols:
        raise ValueError('主用神须来自本题已定位的用神：' + '、'.join(symbols))
    main = primary or (rule.primary if rule else symbols[0] if len(hits) < 2 or topic == '通用' else None)
    basis = rule.basis if rule else (
        '问句涉及多个细项，需确认本次主要观察的结果。' if main is None else '按本类别的通用用神暂查，结合实际问项复核。')
    if primary:
        basis = '由分析者指定主用神。' + basis
    if urgency is not None and urgency not in ('急','缓','待核'):
        raise ValueError('急缓可填急、缓或待核')
    actors = dict(roles or {})
    if first_mover and first_mover not in ('本人','对方','双方未动','同动','待核'):
        raise ValueError('行动顺序可填本人、对方、双方未动、同动或待核')
    actor, counterpart = actors.get('所测人','所测人'), actors.get('对方','对方')
    host_guest = {
        '本人': f'客={actor}，主={counterpart}',
        '对方': f'客={counterpart}，主={actor}',
    }.get(first_mover, '先后不明或未发生，暂不按动静判主客')
    # 代问不自动把日干归给所测人。先标问者，分析时单独指定所测人用神。
    delegation = actors.get('问者') and actors.get('所测人') and actors['问者'] != actors['所测人']
    role_note = '代问：日干先标问者，所测人与其年命须另核归属' if delegation else '日干先标问者'
    emphasis = {'急':'先核主用神宫的神，再看门与实际行动',
                '缓':'先核主用神宫的门与值使，再合参神'}.get(urgency, '急缓待核，神门并看')
    order = ('神','门','星','天地盘干') if urgency == '急' else (
        ('门','神','星','天地盘干') if urgency == '缓' else ('星','门','神','天地盘干'))
    timing = tuple(dict.fromkeys([main, *(rule.timing if rule else ())])) if main else ()
    return {'问项': chosen, '候选问项': hits, '主用神': main, '用神': symbols,
            '评分反向': bool(rule.invert) if rule else False,
            '应期用神': timing, '取用依据': basis, '角色': host_guest,
            '角色资料': actors, '代问说明': role_note, '行动顺序': first_mover or '待核',
            '主客原注': parties, '神门重点': emphasis, '取象顺序': order, '阶段': stage or '待核',
            '观察结果': outcome.strip(), '观察期限': horizon or '未提供'}
